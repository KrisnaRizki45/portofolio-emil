// Dynamically glob project images from assets
const PROJECT_IMAGE_MODULES = import.meta.glob(
  '../assets/projects/*/*.{jpeg,jpg,png,webp}',
  { eager: true, import: 'default' },
)

const PROJECT_IMAGES_BY_SLUG = Object.entries(PROJECT_IMAGE_MODULES).reduce(
  (acc, [path, src]) => {
    const parts = path.split('/')
    // path example: ../assets/projects/msglow/konten1.jpeg -> parts[3] is msglow
    const slug = parts[parts.indexOf('projects') + 1]
    const fileName = parts[parts.length - 1]

    if (slug) {
      if (!acc[slug]) acc[slug] = []
      acc[slug].push({ src, fileName })
    }
    return acc
  },
  {},
)

Object.values(PROJECT_IMAGES_BY_SLUG).forEach((items) => {
  items.sort((a, b) =>
    a.fileName.localeCompare(b.fileName, undefined, {
      numeric: true,
      sensitivity: 'base',
    }),
  )
})

export const PROJECTS = PROJECT_META.map((project) => {
  const images = (PROJECT_IMAGES_BY_SLUG[project.slug] || []).map(
    (item) => item.src,
  )
  const defaultFallback = '/assets/paspoto-emil.jpeg'
  return {
    ...project,
    categoryLabel: PROJECT_CATEGORY_LABELS[project.category] || 'Creative Project',
    images,
    cover: images[0] || defaultFallback,
    banner: images[0] || defaultFallback,
  }
})

